"""Turn the linked event hook into bytes plus the entry offset (src/event_hook.h)."""
import re
import struct
import subprocess
import sys
from pathlib import Path

header = Path('src/event_hook.h').read_text()
const = {k: int(v, 0) for k, v in re.findall(r'#define (EVENT_\w+) (0x[0-9a-f]+|\d+)\b', header)}
b = Path('build/event_hook.elf').read_bytes()
shoff = struct.unpack_from('<Q', b, 40)[0]
shsize, shnum = struct.unpack_from('<HH', b, 58)
for i in range(shnum):
    section = struct.unpack_from('<IIQQQQIIQQ', b, shoff + i * shsize)
    assert section[1] not in (4, 9) or section[5] == 0, 'event hook has relocations'
symbols = {}
for line in subprocess.check_output([sys.argv[1], '-n', 'build/event_hook.elf'], text=True).splitlines():
    fields = line.split()
    if len(fields) == 3:
        symbols[fields[2]] = int(fields[0], 16)
blob = Path('build/event_hook.bin').read_bytes()
rva = const['EVENT_HOOK_RVA']
assert len(blob) == const['EVENT_HOOK_SIZE'], len(blob)
magic = re.search(r'#define EVENT_HOOK_MAGIC "(\w+)"', header).group(1).encode()
assert blob[:8] == magic
assert symbols['eh_header'] == rva
assert symbols['eh_log_entries'] == const['EVENT_LOG_RVA'] + const['EVENT_LOG_OFF_ENTRIES']
assert symbols['eh_table'] == const['EVENT_LOG_RVA'] + const['EVENT_TABLE_OFF']
entry = symbols['eh_entry'] - rva
assert 0x40 <= entry < const['EVENT_HOOK_SIZE']
code = blob
Path('build/event_hook_blob.h').write_text(
    '/* Generated by build_event_hook.py; do not edit. */\n'
    f'#define EVENT_HOOK_ENTRY {entry:#x}\n'
    'static const unsigned char event_hook_blob[]={' + ','.join(map(str, code)) + '};\n')
