"""Prepare reproducible, embedded assets for GT7Patcher."""
import hashlib
import json
from pathlib import Path
import xml.etree.ElementTree as ET

HERE = Path(__file__).resolve().parent
BUILD = HERE / 'build'

def cstring(value):
    return json.dumps(value, ensure_ascii=True).replace('?', r'\?')

def main():
    BUILD.mkdir(exist_ok=True)
    source = HERE / 'data/PPSA01317-original.xml'
    source_metas = ET.parse(source).getroot().findall('Metadata')
    assert len(source_metas) == 7
    assert any(m.get('Name') == 'Debug environment' for m in source_metas)
    metas = [m for m in source_metas if m.get('Name') != 'Debug environment']
    assert len(metas) == 6
    assert all(not any(c in m.get(k, '') for c in '\"\\\r\n') for m in metas for k in ['Name', 'Note'])
    wheel = next(m for m in metas if m.get('Name') == 'Wheel Offset Presets')
    wheel_lines = wheel.findall('./PatchList/Line')
    assert len(wheel_lines) == 1
    assert int(wheel_lines[0].get('Address'), 16) == 0x3896010
    assert bytes.fromhex(wheel_lines[0].get('Value')) == (BUILD / 'wheel_offset_custom.bin').read_bytes()
    header = ['/* Generated by generate.py; do not edit. */']
    header += ['static const char *patch_names[]={' + ','.join(cstring(m.get('Name')) for m in metas) + '};']
    header += ['static const char *patch_notes[]={' + ','.join(cstring(m.get('Note')) for m in metas) + '};']
    header += ['static const char *patch_lines[]={']
    counts = []
    for m in metas:
        lines = m.findall('./PatchList/Line')
        assert all(e.get('Type') == 'bytes' for e in lines)
        counts.append(len(lines))
        xml = ''.join(ET.tostring(e, encoding='unicode').strip() + '\n' for e in lines)
        header.append(cstring(xml) + ',')
    header += ['};', 'static const unsigned patch_counts[]={' + ','.join(map(str, counts)) + '};']
    html = (HERE / 'web/index.html').read_text(encoding='utf-8')
    header += ['static const char web_page[]=' + cstring(html) + ';']
    (BUILD / 'assets.h').write_text('\n'.join(header) + '\n', encoding='utf-8')

    manifest = {'original_xml_sha256': hashlib.sha256(source.read_bytes()).hexdigest(),
                'patch_names': [m.get('Name') for m in metas], 'line_counts': counts,
                'engine': 'GT7-only in-process launch engine; no child ELFs'}
    (BUILD / 'assets.json').write_text(json.dumps(manifest, indent=2) + '\n')
    generate_icon()


def generate_icon():
    png = (HERE / 'assets/icon0.png').read_bytes()
    assert png[:8] == b'\x89PNG\r\n\x1a\n'
    (BUILD/'icon0.png').write_bytes(png)
    param = json.dumps({'applicationCategoryType':66048,'titleId':'GTPS00001',
        'deeplinkUri':'http://127.0.0.1:7210/', 'localizedParameters':{'defaultLanguage':'en-US','en-US':{'titleName':'GT7Patcher'}}})
    (BUILD/'icon.h').write_text('static const unsigned char icon_param[]='+cstring(param)+';\nstatic const unsigned char icon_png[]={'+','.join(map(str,png))+'};\n')

if __name__ == '__main__':
    main()
