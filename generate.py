"""Prepare reproducible, embedded assets for GT7Patcher."""
import hashlib
import json
from pathlib import Path
import re
import struct

HERE = Path(__file__).resolve().parent
BUILD = HERE / 'build'
PATCH_SOURCES = [
    ('Offline mode', 'offline_mode'),
    ('Debug Settings', 'debug_settings'),
    ('Quick Store Rotation', 'quick_store_rotation'),
    ('Unlock Power Pack', 'unlock_power_pack'),
    ('Unlock Vehicle DLCs', 'unlock_vehicle_dlcs'),
    ('Wheel Offset Presets', 'wheel_offset_custom'),
    ('Live Settings', 'live_settings'),
    ('Allow skipping new game intro movie', 'opening_movie_skip'),
]

def cstring(value):
    return json.dumps(value, ensure_ascii=True).replace('?', r'\?')

def object_patch_lines(path):
    """Read ordered .patch.SEQUENCE.ADDRESS sections from an ELF64 object."""
    blob = path.read_bytes()
    assert blob[:6] == b'\x7fELF\x02\x01'
    section_offset = struct.unpack_from('<Q', blob, 0x28)[0]
    section_size, section_count, names_index = struct.unpack_from('<HHH', blob, 0x3a)
    assert section_size == 64 and section_count and names_index < section_count
    sections = [struct.unpack_from('<IIQQQQIIQQ', blob, section_offset + i * section_size)
                for i in range(section_count)]
    names_header = sections[names_index]
    names = blob[names_header[4]:names_header[4] + names_header[5]]
    result = []
    for section in sections:
        end = names.find(b'\0', section[0])
        name = names[section[0]:end].decode('ascii')
        match = re.fullmatch(r'\.patch\.(\d{4})\.([0-9a-f]{8})', name)
        if match:
            offset, size = section[4], section[5]
            result.append((int(match.group(1)), int(match.group(2), 16), blob[offset:offset + size]))
    result.sort()
    assert [sequence for sequence, _, _ in result] == list(range(len(result)))
    assert result
    return [(address, data) for _, address, data in result]

def main():
    BUILD.mkdir(exist_ok=True)
    manifest_path = HERE / 'patches/manifest.json'
    manifest = json.loads(manifest_path.read_text(encoding='utf-8'))
    assert len(manifest) == 9
    assert any(m['name'] == 'Debug environment' and not m['built'] for m in manifest)
    metas = [m for m in manifest if m['built']]
    assert [(m['name'], m['source']) for m in metas] == PATCH_SOURCES
    assert all(not any(c in m[k] for c in '\"\\\r\n') for m in metas for k in ['name', 'note'])
    header = ['/* Generated by generate.py; do not edit. */']
    header += ['static const char *patch_names[]={' + ','.join(cstring(m['name']) for m in metas) + '};']
    header += ['static const char *patch_notes[]={' + ','.join(cstring(m['note']) for m in metas) + '};']
    header += ['static const char *patch_lines[]={']
    counts = []
    for _, stem in PATCH_SOURCES:
        if stem == 'live_settings':
            counts.append(0)
            header.append(cstring('') + ',')
            continue
        lines = object_patch_lines(BUILD / f'{stem}.o')
        counts.append(len(lines))
        xml = ''.join(f'<Line Type="bytes" Address="0x{address:08x}" Value="{data.hex()}" />\n'
                      for address, data in lines)
        header.append(cstring(xml) + ',')
    header += ['};', 'static const unsigned patch_counts[]={' + ','.join(map(str, counts)) + '};']
    html = (HERE / 'web/index.html').read_text(encoding='utf-8')
    cleaner = json.loads((HERE / 'data/cleaner.json').read_text())
    assert cleaner['version'] == 1 and len(cleaner['files']) == 14
    scripts = '<script id="clean-manifest" type="application/json">' + json.dumps(cleaner, separators=(',', ':')) + '</script>\n'
    scripts += '<script id="clean-worker" type="text/plain">' + (HERE / 'web/cleaner-worker.js').read_text(encoding='utf-8') + '</script>\n'
    scripts += '<script>' + (HERE / 'web/cleaner.js').read_text(encoding='utf-8') + '</script>\n'
    assert '<!-- CLEANER_SCRIPTS -->' in html
    html = html.replace('<!-- CLEANER_SCRIPTS -->', scripts)
    (BUILD / 'index.html').write_text(html, encoding='utf-8')
    header += ['static const char web_page[]=' + cstring(html) + ';']
    (BUILD / 'assets.h').write_text('\n'.join(header) + '\n', encoding='utf-8')

    assets = {'patch_manifest_sha256': hashlib.sha256(manifest_path.read_bytes()).hexdigest(),
              'patch_names': [m['name'] for m in metas], 'line_counts': counts,
              'patch_sources': {f'patches/{stem}.S': hashlib.sha256((HERE / 'patches' / f'{stem}.S').read_bytes()).hexdigest()
                                for _, stem in PATCH_SOURCES if stem != 'live_settings'},
              'engine': 'GT7-only in-process launch engine; no child ELFs'}
    (BUILD / 'assets.json').write_text(json.dumps(assets, indent=2) + '\n')
    generate_icon()


def generate_icon():
    png = (HERE / 'assets/icon0.png').read_bytes()
    assert png[:8] == b'\x89PNG\r\n\x1a\n'
    (BUILD/'icon0.png').write_bytes(png)
    param = json.dumps({'applicationCategoryType':66048,'titleId':'GTPS00001',
        'deeplinkUri':'http://127.0.0.1:7210/', 'localizedParameters':{'defaultLanguage':'en-US','en-US':{'titleName':'GT7Patcher'}}})
    (BUILD/'icon.h').write_text('static const unsigned char icon_param[]='+cstring(param)+';\nstatic const unsigned char icon_png[]={'+','.join(map(str,png))+'};\n')

if __name__ == '__main__':
    main()
